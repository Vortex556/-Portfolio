　　你根本听不见谈话内容。只能通过她紧蹙的眉头和轻蔑挑起的眉尾，大致知道，鹿野很烦躁。
　　思及此，隔音法宝刚好被收起，想象中她不耐烦的声音和现实重合：“你做好分内事就是对我最大的帮助。别烦我，就这样。”她挂了电话，皱眉在手机屏幕上点几下，一抬头，看见伫立在原地的你。
　　“出什么状况了吗？”她蹙起的眉头放松下来，平静地看向你。
　　“没什么。”你想起房间里乱成一锅粥的灵，朝她晃晃手中的纸笔，不由得叹了口气：“轨迹比我高考数学几何题乱得多了，我更需要文具辅助辅助。”
　　鹿野点点头，继续处理手机消息。你见她没有什么吩咐，也转过身去。
　　该回去干点正事了。
　　“等等。”鹿野叫住你。
　　她的手伸进皮衣口袋，从里面掏出一个牛皮纸信封递给你，“打开看看。”
　　你疑惑地接下，撕开信封。里面只有一张短短的纸条。
　　“……转正通知？”
　　你猛地抬起头，双眼不由得瞪大。
　　“嗯，”鹿野淡淡地应了声，“别当你那替补组员了，转正好好干吧。”
　　巴掌大的纸条上，简短的一行通知下，正是鹿野极具个性、龙飞凤舞的手写签名。
　　“谢，谢谢大人！”
　　“知道了，”她摆摆手，示意你回去，“感知组的任务量多得超乎想象，别高兴太早。”
　　“嗯嗯！”你连连点头，揣着信封赶紧回现场。身后传来一声若有似无的轻笑。
　　成为正式组员，意味着有更多机会接触鹿野，意味着有更多机会成为“伙伴”，意味着得到更多信任。
　　怎么不算是飞跃式进展呢？
　　
　　……
　　
　　这是第七张废稿。
　　你将这张画得乱七八糟的草稿团成一团，塞进已经鼓鼓囊囊的随身垃圾袋里，烦躁不堪。
　　这简直比我淋浴间下水道缠成一团的头发还要乱，比改版断金阵的灵轨还要乱得多……不能移动灵做区分真是太憋屈了。
　　且不说它们的运动有多复杂，单单是待在这种灵力波动异常紊乱的房间里，你就比平时要焦躁许多。仿佛再凝神看多一秒钟，脑子就要当场爆炸。
　　测灵仪显示屏上，荧光绿的数字和曲线胡乱跳动、毫无规律，看得你心烦。
　　……还是先休息一会吧。
　　你长叹一声，仰起头，闭上眼睛，眼泪瞬间随着眼睑包裹住干涩的眼球。等眼里的刺痛稍稍消退，你复又睁开眼，盯着天花板上活蹦乱跳的灵发愁。
　　其实真的很累了……但你的眼睛还是跟随着那几个灵，心里又在默默记轨迹。
　　左移……下拐……绕了个八字形……接下来是上拐……上拐……上……嗯？
　　某颗你已经能背下轨迹的灵竟不遵守自己的规矩，直直地飞出窗户，当着你的面逃离房间。
　　……？
　　不对劲，它要往哪里去？！
　　有人在操控？！
　　你不管三七二十一，纸笔往兜里一揣，灵活地翻出窗户，纵身一跃！

